#!/usr/bin/env python3
"""Restore only exact JR RA/SW A1 colour leaves in the locked USA effect table."""
from pathlib import Path
import hashlib,json,re,struct
root=Path(__file__).resolve().parents[1]
elf=(root.parent/'disc/SLUS_209.11').read_bytes()
sha=hashlib.sha256(elf).hexdigest()
if sha!='a26e86e59cab447d9b1839ec11ab82b1557230bcc99746b78e3b5d4359dcc6ff':
 raise SystemExit('USA ELF identity mismatch')
ph=struct.unpack_from('<I',elf,28)[0];pe,pn=struct.unpack_from('<HH',elf,42)
def read(address,size):
 for i in range(pn):
  kind,offset,base,_,length,*_=struct.unpack_from('<8I',elf,ph+i*pe)
  if kind==1 and base<=address and address+size<=base+length:
   return elf[offset+address-base:offset+address-base+size]
 raise ValueError('Address outside loaded ELF:'+hex(address))
# Matching USA decomp symbols:EffectPCPFuncTable31DF90 through HBED2 table31EFF8.
# The generated dispatcher1761E0 loads slot1C in each28-byte table (hex).
base=0x31df90;count=106;stride=0x28;slot=0x1c
registered=set(int(x,16) for x in re.findall(r'registerFunction\(0x([0-9a-fA-F]+)',(root/'generated/nocturne/output/register_functions.cpp').read_text()+(root/'src/product/patches.cpp').read_text()))
leaves={};others=[]
for index in range(count):
 table=base+index*stride+slot;address=struct.unpack('<I',read(table,4))[0]
 if not address or address in registered:continue
 raw=read(address,8);jr,store=struct.unpack('<II',raw)
 if jr!=0x03e00008 or store>>16!=0xac85:
  others.append({'index':index,'address':hex(address),'reason':'not an exact two-instruction colour store;not restored by this audit'})
  continue
 offset=store&0xffff
 if offset&0x8000:raise ValueError('Negative store offset requires explicit review')
 leaf=leaves.setdefault(address,{'offset':offset,'indices':[],'table_addresses':[],'words':[f'{jr:08x}',f'{store:08x}'],'sha256':hashlib.sha256(raw).hexdigest()})
 leaf['indices'].append(index);leaf['table_addresses'].append(hex(table))
lines=['// Generated by scripts/magatama_audit_effect_colors.py from the locked USA ELF.', '// Only previously unregistered JR RA;SW A1,offset(A0) colour table handlers.']
for address,leaf in sorted(leaves.items()):
 lines.append(f'MAGATAMA_EFFECT_COLOR(0x{address:08X}u,0x{leaf["offset"]:X}u,{leaf["indices"][0]}u) // table indices '+','.join(map(str,leaf['indices'])))
(root/'src/product/nocturne_effect_color_leaves.inc').write_text('\n'.join(lines)+'\n')
out=root/'build/nocturne-effects/color-audit.json';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(json.dumps({'elf_sha256':sha,'table_base':hex(base),'table_count':count,'table_stride':stride,'colour_slot':slot,'new_leaves':{hex(k):v for k,v in leaves.items()},'other_missing_callbacks':others},indent=2)+'\n')
print(f'Checked{count}colour slots;generated{len(leaves)}exact leaves,{sum(len(v["indices"]) for v in leaves.values())}table bindings;{len(others)}other missing callback(s) left unchanged')
